/* ===== 54. Lab-exam parts (added to PARTS, same rules as 22-…) =====================================
   What the lab exams and practice sets of the course keep asking for: letters on the 7-segment
   (the course's A–Z table), a counter that runs through any list of values (primes, step 3,
   Fibonacci, 0..88), running-LED patterns, PWM, two's complement → sign + magnitude, and a text
   that scrolls over the 4 digits of the EDGE board (a name, a student id). Each one is generated by
   code and checked against a reference model before it is drawn.
   Sequential ones share one generator (ptCycle): a state counter 0..L-1 on D flip-flops with the
   next-state and output logic minimised from tables (unused codes go back to 0, so it starts by
   itself), optional en (count only when 1) and clr (synchronous, to state 0). */

/* the course's letters (SSD A-Z reference), digits as SEG7; ' ' blank, '-' g, '_' d */
const CHAR7_AZ=["abcefg","cdefg","adef","bcdeg","adefg","aefg","abcdfg","bcefg","bc","bcd","efg","def","ace",
  "abcef","abcdef","abefg","abcfg","aef","acdfg","defg","bcdef","cde","bdf","bcg","bcdfg","abdeg"];
function char7(ch){                      // → "abc…" (active-high segments) or null when there is none
  const c=String(ch).toUpperCase();
  if(c>="0" && c<="9"){ const d=+c; return [..."abcdefg"].filter(s=>segOn(s,d)).join(""); }
  if(c>="A" && c<="Z") return CHAR7_AZ[c.charCodeAt(0)-65];
  const SP={" ":"", "-":"g", "_":"d", "=":"dg", "'":"b"};
  return c in SP ? SP[c] : null;
}
const char7Check=v=>{ const bad=[...String(v)].filter(ch=>char7(ch)==null); return bad.length?`no 7-segment pattern for ${bad.map(c=>JSON.stringify(c)).join(" ")} (use 0-9 A-Z space - _ = ')`:null; };

/* "2,3,5,7" · "0..99 step 3" · "0-30/3" · "10..0" (down) — mixed with commas */
function ptValues(txt){
  const out=[];
  for(const part of String(txt).split(/[,;]+/).map(x=>x.trim()).filter(Boolean)){
    const m=/^(\d+)\s*(?:\.\.|-|to)\s*(\d+)(?:\s*(?:step|\/)\s*(\d+))?$/i.exec(part);
    if(m){ const a=+m[1], b=+m[2], k=Math.max(1,+(m[3]||1)); if(a<=b) for(let x=a;x<=b;x+=k) out.push(x); else for(let x=a;x>=b;x-=k) out.push(x); }
    else if(/^\d+$/.test(part)) out.push(+part);
    else return {error:`cannot read ${JSON.stringify(part)} — write values like 2,3,5,7 or 0..99 step 3`};
    if(out.length>64) return {error:"at most 64 values"};
  }
  if(out.length<2) return {error:"give at least 2 values"};
  if(out.some(x=>x>255)) return {error:"values 0..255"};
  return {values:out};
}
const ptValuesCheck=v=>ptValues(v).error||null;

/* state counter 0..L-1 → state vars [{p,n}] (bit 0 first) */
function ptCycle(t, L, clk, en, clr){
  const k=ptLen(L-1), F=Array.from({length:k},()=>t.X("DFF"));
  F.forEach(f=>t.W(clk, f+".clk"));
  const sv=F.map(f=>({p:f+".q", n:f+".qn"})), vars=[...sv];
  if(en) vars.push({p:en, n:null}); if(clr) vars.push({p:clr, n:null});
  const next=m=>{ const s=m&((1<<k)-1); let i=k; const e=en?(m>>(i++))&1:1, c=clr?(m>>i)&1:0;
    return c||s>=L ? 0 : e ? (s+1)%L : s; };
  F.forEach((f,j)=>t.W(ptSop(t, vars, ptMin(vars.length, m=>(next(m)>>j)&1)), f+".d"));
  return sv;
}
/* an output bit as a function of the state (codes ≥ L are don't-care) */
const ptOfState=(t, sv, L, f)=>ptSop(t, sv, ptMin(sv.length, s=>s<L && f(s)), ptMin(sv.length, s=>s>=L));
const ptSeqDrive=(en, clr)=>i=>{ const o={}; if(en) o.en=[1,1,0,1,1,1,0,0,1,1][i%10]; if(clr) o.clr=(i===23||i===61)?1:0; return o; };
const ptSeqNext=(s, v, L, en, clr)=>(clr&&v.clr)?0:(!en||v.en)?(s+1)%L:s;

